/**
 * Localise free text from legacy fixtures or API fallback data.  Exact phrase
 * matches are preferred; remaining Traditional-Chinese text receives a
 * character-level conversion so legacy output does not regress to Simplified.
 */
export function localizeText(source: string, locale: AppLocale = getActiveLocale()): string {
  if (!source) return source
  const dictionary = dictionaries[locale]
  const exact = dictionary[source]
  if (exact) return exact

  let result = source
  // Support the interpolated copy used by counters, error wrappers and
  // anomaly summaries (for example, "共 3 条" or "无法读取：...").
  for (const [from, to] of phraseEntries[locale]) {
    if (!from.includes('{')) continue
    const names: string[] = []
    const pattern = from.replace(/[.*+?^${}()|[\]\\]/g, '\\$&').replace(/\\\{([A-Za-z0-9_]+)\\\}/g, (_token, name: string) => {
      names.push(name)
      return '(.+?)'
    })
    const match = new RegExp(`^${pattern}$`).exec(result)
    if (!match) continue
    const values: TranslationValues = {}
    names.forEach((name, index) => { values[name] = match[index + 1] })
    return interpolate(to, values)
  }
  for (const [from, to] of phraseEntries[locale]) {
    if (from.length < 2 || !result.includes(from)) continue
    result = result.split(from).join(to)
  }

  if (locale === 'zh-Hant') {
    result = Array.from(result, (character) => simplifiedCharacters[character] ?? character).join('')
  }
  return result
}

