/** Recursively localise display payloads while preserving object keys and canonical IDs/codes. */
export function localizePayload<T>(value: T, locale: AppLocale = getActiveLocale(), fieldName = ''): T {
  if (typeof value === 'string') return (protectedField.test(fieldName) ? value : localizeText(value, locale)) as T
  if (Array.isArray(value)) return value.map((item) => localizePayload(item, locale, fieldName)) as T
  if (!value || typeof value !== 'object' || value instanceof Date) return value

  const source = value as Record<string, unknown>
  const localized = Object.fromEntries(Object.entries(source).map(([key, item]) => [key, localizePayload(item, locale, key)]))
  return localized as T
}
