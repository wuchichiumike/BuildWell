/**
 * Client-side locale primitives shared by React views and API adapters.
 *
 * Business identifiers remain canonical (for example, `PROJECT_OWNER` and
 * `PENDING_APPROVAL`).  Only human-facing labels and free text are localized.
 */
export type AppLocale = 'zh-Hant' | 'en'

export type TranslationValues = Record<string, string | number | boolean | null | undefined>

export const DEFAULT_LOCALE: AppLocale = 'zh-Hant'
export const LOCALE_STORAGE_KEY = 'zhufulian.locale'

export const localeOptions: ReadonlyArray<{ value: AppLocale; label: string }> = [
  { value: 'zh-Hant', label: '繁體中文' },
  { value: 'en', label: 'English' },
]

const browserLocale = (locale: AppLocale) => locale === 'en' ? 'en-GB' : 'zh-Hant-HK'

export function normalizeLocale(value?: string | null): AppLocale {
  const normalized = value?.trim().toLowerCase() ?? ''
  if (normalized === 'en' || normalized.startsWith('en-')) return 'en'
  return 'zh-Hant'
}

export function localeForApi(locale: AppLocale = getActiveLocale()): 'zh-TW' | 'en' {
  return locale === 'en' ? 'en' : 'zh-TW'
}

export function detectLocale(): AppLocale {
  if (typeof window === 'undefined') return DEFAULT_LOCALE

  try {
    const persisted = window.localStorage.getItem(LOCALE_STORAGE_KEY)
    if (persisted) return normalizeLocale(persisted)
  } catch {
    // Storage can be unavailable in privacy-restricted contexts.
  }

  const documentLocale = typeof document !== 'undefined' ? document.documentElement.lang : ''
  if (documentLocale) return normalizeLocale(documentLocale)
  return normalizeLocale(window.navigator.language)
}

let activeLocale: AppLocale = detectLocale()
const localeSubscribers = new Set<(locale: AppLocale) => void>()

export function getActiveLocale(): AppLocale {
  return activeLocale
}

export function setActiveLocale(value: AppLocale | string): AppLocale {
  activeLocale = normalizeLocale(value)
  if (typeof document !== 'undefined') document.documentElement.lang = activeLocale === 'en' ? 'en' : 'zh-Hant'
  if (typeof window !== 'undefined') {
    try {
      window.localStorage.setItem(LOCALE_STORAGE_KEY, activeLocale)
    } catch {
      // The application still works when persistence is not available.
    }
  }
  localeSubscribers.forEach((subscriber) => subscriber(activeLocale))
  return activeLocale
}

export function subscribeLocale(subscriber: (locale: AppLocale) => void): () => void {
  localeSubscribers.add(subscriber)
  return () => localeSubscribers.delete(subscriber)
}

