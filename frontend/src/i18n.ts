function interpolate(template: string, values?: TranslationValues): string {
  if (!values) return template
  return template.replace(/\{([A-Za-z0-9_]+)\}/g, (token, name) => {
    const value = values[name]
    return value === undefined || value === null ? token : String(value)
  })
}

/** Translate semantic keys or a legacy Simplified-Chinese source string. */
export function translate(key: string, values?: TranslationValues, locale: AppLocale = getActiveLocale()): string {
  return interpolate(dictionaries[locale][key] ?? key, values)
}

