export function formatNumber(value: string | number | null | undefined, locale: AppLocale = getActiveLocale(), options?: Intl.NumberFormatOptions): string {
  if (value === null || value === undefined || value === '') return ''
  const numeric = typeof value === 'number' ? value : Number(String(value).replace(/,/g, ''))
  if (!Number.isFinite(numeric)) return String(value)
  return new Intl.NumberFormat(browserLocale(locale), { maximumFractionDigits: 3, ...options }).format(numeric)
}

